#!/usr/bin/env node
// Generates src/svg/icons.ts and src/svg/signs.ts from third-party graphics so the library
// ships without runtime dependencies:
//
//   * Pinhead icons (CC0 1.0, https://github.com/waysidemapping/pinhead) are read from the
//     pinned devDependency and inlined as path data.
//   * German StVO road signs (public domain, § 5 UrhG) are read from assets/stvo/ (see
//     scripts/fetch-stvo.mjs), stripped of editor metadata, and their IDs are namespaced so
//     several signs can be embedded in one SVG document.
//
// Usage: node scripts/build-assets.mjs   (the generated files are committed)

import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const PINHEAD_DIR = join(dirname(require.resolve('@waysidemapping/pinhead/package.json')), 'dist', 'icons')
const PINHEAD_VERSION = JSON.parse(
  await readFile(join(dirname(PINHEAD_DIR), '..', 'package.json'), 'utf8'),
).version

/** osm-lanes icon key → Pinhead icon id. */
const ICONS = {
  // transport modes (access:lanes and friends)
  motor_vehicle: 'car',
  car: 'car',
  hgv: 'truck',
  bus: 'bus',
  psv: 'bus',
  taxi: 'taxi',
  hov: 'people_in_car',
  bicycle: 'bicycle',
  motorcycle: 'motorcycle',
  foot: 'person_walking',
  wheelchair: 'wheelchair',
  tram: 'tram_on_tram_track',
  // destination:symbol values (https://wiki.openstreetmap.org/wiki/Key:destination:symbol)
  airport: 'plane_ascending',
  aerodrome: 'plane_ascending',
  train_station: 'transit_vehicle_on_railway_track',
  bus_station: 'bus',
  ferry: 'ferryboat',
  port: 'ships_wheel',
  harbour: 'ships_wheel',
  hospital: 'hospital_h',
  industrial: 'industrial_building',
  centre: 'town_buildings',
  city_centre: 'town_buildings',
  city: 'city_buildings',
  parking: 'wide_p',
  fuel: 'gasoline_pump',
}

function extractPath(svg, id) {
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (paths.length !== 1) throw new Error(`Pinhead icon ${id}: expected 1 path, found ${paths.length}`)
  if (!/viewBox="0 0 15 15"/.test(svg)) throw new Error(`Pinhead icon ${id}: unexpected viewBox`)
  return paths[0]
}

function cleanSign(svg, key) {
  const prefix = `stvo${key.replace(/[^a-z0-9]/gi, '_')}_`
  let s = svg
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!DOCTYPE[\s\S]*?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/<sodipodi:namedview[\s\S]*?(\/>|<\/sodipodi:namedview>)/g, '')
    .replace(/<title[\s\S]*?<\/title>/g, '')
  if (/<(script|foreignObject|image|style)\b/i.test(s)) throw new Error(`Sign ${key}: unsupported element`)
  if (/\son\w+=/i.test(s)) throw new Error(`Sign ${key}: event handler attribute`)

  const root = s.match(/<svg\b([^>]*)>/)
  if (!root) throw new Error(`Sign ${key}: no <svg> root`)
  const attrs = root[1]
  let viewBox = attrs.match(/\sviewBox="([^"]+)"/)?.[1]
  if (!viewBox) {
    const w = parseFloat(attrs.match(/\swidth="([\d.]+)/)?.[1] ?? '')
    const h = parseFloat(attrs.match(/\sheight="([\d.]+)/)?.[1] ?? '')
    if (!w || !h) throw new Error(`Sign ${key}: no viewBox or size`)
    viewBox = `0 0 ${w} ${h}`
  }
  let inner = s.slice(root.index + root[0].length, s.lastIndexOf('</svg>'))
  inner = inner
    // drop editor-namespaced attributes and elements
    .replace(/\s(sodipodi|inkscape|xml):[\w-]+="[^"]*"/g, '')
    .replace(/<(sodipodi|inkscape):[\s\S]*?(\/>|<\/\1:[\w-]+>)/g, '')
    // namespace IDs and references so multiple signs can share one document
    .replace(/\sid="([^"]+)"/g, ` id="${prefix}$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${prefix}$1)`)
    .replace(/\s(?:xlink:)?href="#([^"]+)"/g, ` href="#${prefix}$1"`)
    .replace(/-?inkscape-font-specification:[^;"]*;?/g, '')
    // 0.01 user units is far below a pixel for these 600-unit signs
    .replace(/(\d+\.\d{2})\d+/g, '$1')
    // collapse whitespace between tags and inside attribute-free gaps
    .replace(/>\s+</g, '><')
    .replace(/\s{2,}/g, ' ')
    .trim()
  const [, , w, h] = viewBox.split(/[\s,]+/).map(Number)
  return { viewBox, width: w, height: h, body: inner }
}

const banner = (what) =>
  `// GENERATED by scripts/build-assets.mjs — do not edit by hand.\n// ${what}\n\n`

async function main() {
  // --- icons
  const icons = {}
  for (const [key, id] of Object.entries(ICONS)) {
    const svg = await readFile(join(PINHEAD_DIR, `${id}.svg`), 'utf8')
    icons[key] = { pinhead: id, d: extractPath(svg, id) }
  }
  const iconsTs =
    banner(
      `Icons from Pinhead v${PINHEAD_VERSION} (https://github.com/waysidemapping/pinhead), CC0 1.0 (public domain). Each path uses a 15×15 viewBox.`,
    ) +
    `export interface IconDef {\n  /** Pinhead icon id. */\n  pinhead: string\n  /** SVG path data in a 0 0 15 15 box. */\n  d: string\n}\n\n` +
    `export const ICONS: Readonly<Record<string, IconDef>> = ${JSON.stringify(icons, null, 2)}\n`
  await writeFile(join(ROOT, 'src', 'svg', 'icons.ts'), iconsTs)

  // --- signs
  const sources = JSON.parse(await readFile(join(ROOT, 'assets', 'stvo', 'sources.json'), 'utf8'))
  const signs = {}
  for (const key of Object.keys(sources).sort()) {
    const svg = await readFile(join(ROOT, 'assets', 'stvo', `${key}.svg`), 'utf8')
    signs[key] = { ...cleanSign(svg, key), source: sources[key].page }
  }
  const signsTs =
    banner(
      'German road signs (StVO) from Wikimedia Commons — official works in the public domain under § 5 UrhG. Provenance per sign: assets/stvo/sources.json.',
    ) +
    `export interface SignDef {\n  viewBox: string\n  width: number\n  height: number\n  /** Inner SVG markup (IDs namespaced). */\n  body: string\n  /** Wikimedia Commons file page. */\n  source: string\n}\n\n` +
    `export const SIGNS: Readonly<Record<string, SignDef>> = ${JSON.stringify(signs, null, 2)}\n`
  await writeFile(join(ROOT, 'src', 'svg', 'signs.ts'), signsTs)
  console.log(`icons: ${Object.keys(icons).length}, signs: ${Object.keys(signs).length}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
